def used():
    out = set()
    files = glob.glob(f'{ROOT}/src/**/*.vue', recursive=True) + glob.glob(f'{ROOT}/src/**/*.js', recursive=True)
    for f in files:
        s = open(f, encoding='utf-8').read()
        out |= set(m.group(1) for m in re.finditer(r"\bt\('phos',\s*'((?:[^'\\]|\\.)*)'", s))
        out |= set((m.group(1), m.group(2)) for m in re.finditer(r"\bn\('phos',\s*'((?:[^'\\]|\\.)*)',\s*'((?:[^'\\]|\\.)*)'", s))
    return out


missing = [k for k in used() if k not in DE]
if missing:
    print('missing:', *missing, sep='\n  ')
trans = {}
for k, v in DE.items():
    trans[f'_{k[0]}_::_{k[1]}_' if isinstance(k, tuple) else k] = v
plural = 'nplurals=2; plural=(n != 1);'
for lang in ('de', 'de_DE'):
    with open(f'{ROOT}/l10n/{lang}.json', 'w', encoding='utf-8') as f:
        f.write('{ "translations": ' + json.dumps(trans, ensure_ascii=False, indent=4) + ',"pluralForm" :"' + plural + '"\n}\n')
    with open(f'{ROOT}/l10n/{lang}.js', 'w', encoding='utf-8') as f:
        f.write('OC.L10N.register(\n    "phos",\n    ' + json.dumps(trans, ensure_ascii=False, indent=4).replace('\n', '\n    ') + ',\n"' + plural + '");\n')
sys.exit(1 if missing else 0)
